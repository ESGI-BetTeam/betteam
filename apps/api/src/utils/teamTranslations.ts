/**
 * Traduit le nom d'une équipe de l'anglais vers le français
 * Si aucune traduction n'est trouvée, retourne le nom original
 */
export function translateTeamName(name: string): string {
  return nationalTeamTranslations[name] ?? name;
}

/**
 * Traduit un objet équipe (modifie le champ name)
 */
export function translateTeam<T extends { name: string }>(team: T): T {
  return {
    ...team,
    name: translateTeamName(team.name),
  };
}

/**
 * Traduit une liste d'équipes
 */
export function translateTeams<T extends { name: string }>(teams: T[]): T[] {
  return teams.map(translateTeam);
}
